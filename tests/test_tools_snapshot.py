def test_tool_count():
    assert len(server.TOOLS) == EXPECTED_COUNT


def test_tool_names_and_order():
    actual = [t.name for t in server.TOOLS]
    assert actual == EXPECTED_TOOL_NAMES


def test_schema_hash_unchanged():
    """The JSON-serialized schemas must match the pre-refactor snapshot."""
    snapshot = json.dumps(
        [t.model_dump() for t in server.TOOLS],
        sort_keys=True,
        ensure_ascii=False,
    )
    h = hashlib.sha256(snapshot.encode()).hexdigest()
    assert h == "3794e93d4bc24be761be4b37483888fca9adcbeeb4027cc675be0b4d05facbb7"


def test_no_duplicate_tool_names():
    names = [t.name for t in server.TOOLS]
    assert len(names) == len(set(names))
